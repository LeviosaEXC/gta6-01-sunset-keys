// Small math and formatting helpers shared by every system.
export function clamp(v, a, b) { return Math.max(a, Math.min(b, v)); }
export function lerp(a, b, t) { return a + (b - a) * t; }
export function degToRad(d) { return (d * Math.PI) / 180; }
export function distance2D(ax, az, bx, bz) { return Math.hypot(ax - bx, az - bz); }
export function angleTo(ax, az, bx, bz) { return Math.atan2(bx - ax, bz - az); }
export function angleLerp(a, b, t) {
  let d = b - a;
  while (d > Math.PI) d -= Math.PI * 2;
  while (d < -Math.PI) d += Math.PI * 2;
  return a + d * clamp(t, 0, 1);
}
export function formatCash(n) { return Math.floor(n).toLocaleString('en-US'); }
export function formatClock(hour) {
  const h = Math.floor(hour) % 24;
  const m = Math.floor((hour % 1) * 60);
  return String(h).padStart(2, '0') + ':' + String(m).padStart(2, '0');
}
export function pick(arr, rng) { return arr[Math.floor(rng() * arr.length)]; }
export function hashString(s) {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619); }
  return h >>> 0;
}
